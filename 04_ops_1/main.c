/*
 * ops.c
 *
 *  Experiment with integers to see the operators
 */
#include <stdio.h>

int main(void)
{
	printf("3 + 2 is %d\n", 3 + 2);
	printf("3 - 2 is %d\n", 3 - 2);
	printf("3 * 2 is %d\n", 3 * 2);
	printf("3 / 2 is %d\n", 3 / 2);
	printf("10 / 9 is %d\n", 10 / 9);
	printf("3 %% 2 is %d\n", 3 % 2); //have to use two % to use one operator

	return (0);
}

